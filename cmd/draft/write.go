package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// guardPath refuses to write anywhere inside _drafts. That folder is off limits
// to this tool, unconditionally.
func guardPath(path string) error {
	abs, err := filepath.Abs(path)
	if err != nil {
		return err
	}
	for _, part := range strings.Split(filepath.ToSlash(abs), "/") {
		if part == "_drafts" {
			return fmt.Errorf("refusing to write inside _drafts: %s", path)
		}
	}
	return nil
}

func loadEntries(path string) ([]Entry, error) {
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var entries []Entry
	if err := json.Unmarshal(raw, &entries); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return entries, nil
}

// writeEntries merges new entries into a data file, deduplicating by URL and
// sorting by title -- the same shape `make data-sort` produces.
func writeEntries(path string, existing []Entry, added []Entry) (int, error) {
	if err := guardPath(path); err != nil {
		return 0, err
	}
	seen := map[string]bool{}
	for _, e := range existing {
		seen[strings.ToLower(e.URL)] = true
	}
	merged := append([]Entry{}, existing...)
	n := 0
	for _, e := range added {
		k := strings.ToLower(e.URL)
		if seen[k] || e.Title == "" {
			continue
		}
		seen[k] = true
		merged = append(merged, e)
		n++
	}
	if n == 0 {
		return 0, nil
	}
	sort.SliceStable(merged, func(i, j int) bool { return merged[i].Title < merged[j].Title })

	// Encode with HTML escaping off, otherwise "&" in existing titles would be
	// rewritten to "\u0026" and every such line would show up as a spurious diff.
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(merged); err != nil {
		return 0, err
	}
	return n, os.WriteFile(path, buf.Bytes(), 0o644)
}

// appendRecipeLinks inserts bullets at the end of the "## Recipe links" section
// of recipes.md, just before the "### Cooking videos" subsection.
func appendRecipeLinks(path string, items []Item) (int, error) {
	if err := guardPath(path); err != nil {
		return 0, err
	}
	if len(items) == 0 {
		return 0, nil
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return 0, err
	}
	content := string(raw)

	secIdx := strings.Index(content, "\n## Recipe links\n")
	if secIdx == -1 {
		return 0, fmt.Errorf("%s: '## Recipe links' section not found", path)
	}
	// Insert before the first subsection that follows, or before the next
	// top-level section, whichever comes first.
	rest := content[secIdx+1:]
	insertAt := len(content)
	for _, marker := range []string{"\n### ", "\n## "} {
		if i := strings.Index(rest[len("## Recipe links\n"):], marker); i != -1 {
			cand := secIdx + 1 + len("## Recipe links\n") + i
			if cand < insertAt {
				insertAt = cand
			}
		}
	}

	var b strings.Builder
	n := 0
	for _, it := range items {
		if strings.Contains(content, it.URL) {
			continue
		}
		b.WriteString(fmt.Sprintf("- [%s](%s)\n", it.Title, it.URL))
		n++
	}
	if n == 0 {
		return 0, nil
	}
	updated := content[:insertAt] + b.String() + content[insertAt:]
	return n, os.WriteFile(path, []byte(updated), 0o644)
}

// writeDraft renders the review file: the feed block to paste into feed.md,
// plus anything that needs a human decision.
func writeDraft(path string, date string, feed, review, texts, recipes, skipped, ratings []Item) error {
	if err := guardPath(path); err != nil {
		return err
	}
	var b strings.Builder

	b.WriteString("# draft " + date + "\n\n")
	b.WriteString("Generated by `make draft`. Nothing here is published until you move it.\n")
	b.WriteString("This file is gitignored.\n\n")

	b.WriteString("## Feed block\n\n")
	if len(feed) == 0 {
		b.WriteString("_No feed links._\n\n")
	} else {
		b.WriteString("Add your comment after each dash, then run `make draft-apply` " +
			"to prepend this block to content/feed.md.\n\n")
		b.WriteString("<!-- feed:begin -->\n")
		b.WriteString(renderFeedDays(feed))
		b.WriteString("<!-- feed:end -->\n\n")
	}

	if len(review) > 0 {
		b.WriteString("## Needs review\n\n")
		b.WriteString("These were resolved from another source by search, so the match " +
			"may be wrong. Check each one, then paste the good entries into the data " +
			"file and run `make data-sort` to re-sort.\n\n")

		for _, group := range []struct {
			kind Kind
			file string
		}{
			{KindMovie, movieData},
			{KindBook, bookData},
		} {
			var items []Item
			for _, it := range review {
				if it.Kind == group.kind {
					items = append(items, it)
				}
			}
			if len(items) == 0 {
				continue
			}
			b.WriteString("### " + group.file + "\n\n")
			b.WriteString("```json\n")
			for _, it := range items {
				b.WriteString(jsonEntryFragment(Entry{Title: it.Title, URL: it.URL}))
			}
			b.WriteString("```\n\n")
			for _, it := range items {
				b.WriteString(fmt.Sprintf("- %s — from %s", it.Title, it.From))
				if it.Note2 != "" {
					b.WriteString(" (" + it.Note2 + ")")
				}
				b.WriteString("\n")
			}
			b.WriteString("\n")
		}
	}

	if len(ratings) > 0 {
		b.WriteString("## Movie ratings\n\n")
		b.WriteString("Formatted for the reviews list in `content/blog/movies.md`. " +
			"Adjust the scores you want to change, then paste them in.\n\n")
		b.WriteString("```md\n")
		for _, it := range ratings {
			if it.URL == "" {
				b.WriteString(fmt.Sprintf("- %s %d/5\n", it.Body, it.Rating))
				continue
			}
			b.WriteString(fmt.Sprintf("- [%s](%s) %d/5\n", it.Title, it.URL, it.Rating))
		}
		b.WriteString("```\n\n")

		var flagged []Item
		for _, it := range ratings {
			if it.Note2 != "" {
				flagged = append(flagged, it)
			}
		}
		if len(flagged) > 0 {
			b.WriteString("Check these, the lookup was not a clean match:\n\n")
			for _, it := range flagged {
				b.WriteString(fmt.Sprintf("- you wrote %q — %s\n", it.Body, it.Note2))
			}
			b.WriteString("\n")
		}
	}

	if len(skipped) > 0 {
		b.WriteString("## Filtered out\n\n")
		b.WriteString("Kept out of the feed by the host filter. Move any you actually " +
			"want up into the feed block above.\n\n")
		for _, it := range skipped {
			b.WriteString(fmt.Sprintf("- [%s](%s)\n", it.Title, it.URL))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Text\n\n")
	if len(texts) == 0 {
		b.WriteString("_No loose text._\n")
	} else {
		b.WriteString("Prose with no link. Keep what you want, delete the rest.\n\n")
		for _, it := range texts {
			b.WriteString(fmt.Sprintf("- (%s) %s\n",
				it.Note.When().Format("2006-01-02"), strings.TrimSpace(it.Body)))
		}
	}
	b.WriteString("\n")

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

// jsonEntryFragment renders one entry exactly as it appears inside book.json or
// movie.json -- two-space indent, trailing comma -- so it can be pasted straight
// into the array without reformatting.
func jsonEntryFragment(e Entry) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false) // keep "&" readable, as the data files have it
	enc.SetIndent("  ", "  ")
	if err := enc.Encode(e); err != nil {
		return ""
	}
	return "  " + strings.TrimRight(buf.String(), "\n") + ",\n"
}

// renderFeedDays groups feed links under one dated heading per day they were
// posted, newest day first to match the order of content/feed.md. Links keep
// their within-day order.
func renderFeedDays(feed []Item) string {
	byDay := map[string][]Item{}
	var order []string
	for _, it := range feed {
		key := it.Note.When().Format("2006-01-02")
		if _, seen := byDay[key]; !seen {
			order = append(order, key)
		}
		byDay[key] = append(byDay[key], it)
	}
	sort.Sort(sort.Reverse(sort.StringSlice(order)))

	var b strings.Builder
	for i, key := range order {
		if i > 0 {
			b.WriteString("\n")
		}
		day, err := time.Parse("2006-01-02", key)
		heading := key
		if err == nil {
			heading = day.Format("02-01-2006")
		}
		b.WriteString("### " + heading + "\n\n")
		for _, it := range byDay[key] {
			b.WriteString(fmt.Sprintf("- [%s](%s) - \n", it.Title, it.URL))
		}
	}
	return b.String()
}

// applyFeedBlock moves the marked feed block from the draft file into feed.md,
// inserting it above the most recent dated entry.
func applyFeedBlock(draftPath, feedPath string) error {
	if err := guardPath(feedPath); err != nil {
		return err
	}
	draft, err := os.ReadFile(draftPath)
	if err != nil {
		return err
	}
	s := string(draft)
	start := strings.Index(s, "<!-- feed:begin -->")
	end := strings.Index(s, "<!-- feed:end -->")
	if start == -1 || end == -1 || end < start {
		return fmt.Errorf("%s: no feed block markers found", draftPath)
	}
	block := strings.TrimSpace(s[start+len("<!-- feed:begin -->") : end])
	if block == "" {
		return fmt.Errorf("%s: feed block is empty", draftPath)
	}

	feed, err := os.ReadFile(feedPath)
	if err != nil {
		return err
	}
	fs := string(feed)
	idx := strings.Index(fs, "\n### ")
	if idx == -1 {
		return fmt.Errorf("%s: no dated entries found", feedPath)
	}
	updated := fs[:idx+1] + block + "\n\n" + fs[idx+1:]
	return os.WriteFile(feedPath, []byte(updated), 0o644)
}
